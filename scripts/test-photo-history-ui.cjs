const assert = require('node:assert/strict');
const path = require('node:path');
const puppeteer = require('puppeteer-core');
const {browserPreview} = require('./lib/browser-preview.cjs');
async function run() {
  const preview = await browserPreview(path.join(__dirname,'fixtures/photo-history-preview.tsx'), {'@/components/providers/auth-provider$':path.join(__dirname,'fixtures/photo-history-mocks.ts')});
  const browser = await puppeteer.launch({executablePath:process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
  try {
    const page = await browser.newPage(); const errors=[];
    page.on('pageerror',e=>errors.push(e.message));
    await page.setRequestInterception(true);
    page.on('request',request=>request.url().includes('/api/photos/view/') ? request.respond({status:200,contentType:'image/svg+xml',body:'<svg xmlns="http://www.w3.org/2000/svg" width="1200" height="800"><rect width="1200" height="800" fill="#64748b"/></svg>'}):request.continue());
    const clickText = text=>page.evaluate(text=>{const button=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===text&&!b.closest('[inert]'));if(!button)throw Error('Missing '+text);button.click();},text);
    await page.setViewport({width:1440,height:960});await page.goto(preview.url);
    await page.waitForFunction(()=>document.body.textContent.includes('Images (3)'));
    assert.equal(await page.evaluate(()=>window.photoFixture.calls.filter(x=>x.endsWith('/summary')).length),1,'visible rows batched');
    const aligned = await page.$$eval('[data-record-actions="row"]',groups=>groups.every(group=>{
      const boxes=[...group.querySelectorAll(':scope > button')].map(n=>n.getBoundingClientRect());
      return boxes.every(box=>Math.abs(box.height-32)<1&&Math.abs(box.y-boxes[0].y)<1);
    }));
    assert.equal(aligned,true,'Images and Revert must share one baseline and height');
    await clickText('Images (3)');await page.waitForSelector('[role="dialog"]');
    await page.waitForFunction(()=>document.body.textContent.includes('Receipt SM/PR/005'));
    assert.equal(await page.evaluate(()=>document.body.style.overflow),'hidden');
    assert.ok(await page.evaluate(()=>document.body.textContent.includes('3:45:12 pm IST')));
    assert.equal(await page.$$eval('[role="dialog"] a[download]',nodes=>nodes.length),0);
    assert.equal(await page.$$eval('[role="dialog"] button',nodes=>nodes.some(n=>/^(approve|delete|download|upload)\b/i.test(n.textContent.trim()))),false);
    await page.waitForFunction(()=>[...document.querySelectorAll('[role="dialog"]')].every(n=>n.getAnimations().every(a=>a.playState==='finished')));
    await page.screenshot({path:path.join(preview.output,'photo-gallery-desktop.png')});
    await page.click('button[aria-label^="View photo uploaded"]');
    await page.waitForSelector('img[src^="blob:"]');
    await page.click('button[aria-label="Zoom in"]');
    await page.waitForFunction(()=>document.body.textContent.includes('130%'));
    const imageBox = await page.$eval('img[src^="blob:"]',n=>{const b=n.getBoundingClientRect();return {x:b.x+b.width/2,y:b.y+b.height/2};});
    await page.mouse.move(imageBox.x,imageBox.y);
    await page.mouse.wheel({deltaY:80});
    assert.ok(Math.abs(await page.$eval('img[src^="blob:"]',n=>new DOMMatrix(n.style.transform).a)-1.3)<0.001,'Normal wheel must not zoom');
    await page.keyboard.down('Control');await page.mouse.wheel({deltaY:-100});await page.keyboard.up('Control');
    await page.waitForFunction(()=>new DOMMatrix(document.querySelector('img[src^="blob:"]').style.transform).a>1.3);
    await page.keyboard.press('Escape');
    await page.waitForFunction(()=>document.querySelectorAll('[role="dialog"]').length===1);
    await page.keyboard.press('Escape');await page.waitForFunction(()=>!document.querySelector('[role="dialog"]'));
    assert.equal(await page.$eval('input[aria-label="History search"]',n=>n.value),'PO-001');
    await clickText('Photos expired');await page.waitForFunction(()=>document.body.textContent.includes('2 photos expired'));
    assert.equal(await page.$$eval('[role="dialog"] img',nodes=>nodes.length),0);
    await page.keyboard.press('Escape');await page.waitForFunction(()=>!document.querySelector('[role="dialog"]'));
    await page.setViewport({width:390,height:844,isMobile:true,hasTouch:true});
    await page.waitForFunction(()=>document.body.textContent.includes('Images (3)'));
    assert.equal(await page.$$eval('[data-record-actions="grid"] > button, [data-record-actions="card"] > button',nodes=>nodes.every(n=>Math.abs(n.getBoundingClientRect().height-40)<1)),true,'Mobile action targets have consistent height');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Mobile actions must not overflow the viewport');
    await clickText('Images (3)');await page.waitForFunction(()=>document.body.textContent.includes('Receipt SM/PR/005'));
    await page.waitForFunction(()=>[...document.querySelectorAll('[role="dialog"]')].every(n=>n.getAnimations().every(a=>a.playState==='finished')));
    await page.screenshot({path:path.join(preview.output,'photo-gallery-mobile.png')});
    assert.equal(await page.$eval('[role="dialog"]',n=>n.getBoundingClientRect().width<=window.innerWidth),true);
    await page.click('button[aria-label^="View photo uploaded"]');await page.waitForSelector('img[src^="blob:"]');
    await page.click('button[aria-label="Zoom in"]');await page.waitForFunction(()=>document.body.textContent.includes('130%'));
    await clickText('Fit / reset');
    const touch = await page.$eval('img[src^="blob:"]',n=>{const b=n.getBoundingClientRect();return{x:b.x+b.width/2,y:b.y+b.height/2};});
    const cdp=await page.createCDPSession();
    await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:touch.x-25,y:touch.y,id:1},{x:touch.x+25,y:touch.y,id:2}]});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:touch.x-30,y:touch.y,id:1},{x:touch.x+30,y:touch.y,id:2}]});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:touch.x-60,y:touch.y,id:1},{x:touch.x+60,y:touch.y,id:2}]});
    await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
    await page.waitForFunction(()=>new DOMMatrix(document.querySelector('img[src^="blob:"]').style.transform).a>1);
    await cdp.detach();
    await page.screenshot({path:path.join(preview.output,'photo-viewer-mobile.png')});
    await page.keyboard.press('Escape'); await page.keyboard.press('Escape');
    await page.waitForFunction(()=>!document.querySelector('[role="dialog"]'));
    await page.setViewport({width:320,height:780,isMobile:true,hasTouch:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,'Narrow mobile layout must remain bounded');
    await page.screenshot({path:path.join(preview.output,'photo-actions-mobile.png')});
    assert.deepEqual(errors,[]);
    console.log('PASS: desktop/mobile batched counts, read-only gallery, IST, expired state, zoom, overlay/keyboard close and preserved filters.');
    console.log('Screenshots: '+preview.output);
  } finally {await browser.close();await preview.close();}
}
run().catch(e=>{console.error(e);process.exitCode=1;});
